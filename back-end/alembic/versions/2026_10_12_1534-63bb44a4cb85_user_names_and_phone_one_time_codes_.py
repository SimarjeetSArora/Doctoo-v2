def _split_full_name(full_name: str) -> tuple[str | None, str, str | None, str]:
    """'Dr. Simarjeet Singh Arora' -> ('Dr.', 'Simarjeet', 'Singh', 'Arora')."""
    words = full_name.split()
    salutation = None
    if words and words[0].rstrip(".").lower() in _SALUTATIONS and len(words) > 1:
        salutation = _SALUTATIONS[words.pop(0).rstrip(".").lower()]
    if not words:
        return salutation, full_name.strip() or "-", None, ""
    first = words[0]
    last = words[-1] if len(words) > 1 else ""
    middle = " ".join(words[1:-1]) or None
    return salutation, first, middle, last


